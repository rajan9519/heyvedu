import AppKit
import ApplicationServices
import Carbon.HIToolbox

/// Inserts text at the cursor of the frontmost app by briefly taking over the
/// clipboard and posting ⌘V, then restoring the previous clipboard contents.
final class TextInserter {
    enum Outcome: Equatable {
        /// ⌘V was sent and the previous clipboard comes back shortly.
        case pasted
        /// Nothing focused can take text, so the text was left on the clipboard instead.
        case noTextField
        /// The app the text was meant for quit or couldn't be brought back to the front,
        /// so the text was left on the clipboard instead.
        case targetUnavailable(appName: String?)
    }

    private static let restoreDelay: Duration = .milliseconds(500)
    /// nspasteboard.org markers so clipboard managers skip our temporary entry.
    private static let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    /// - Parameter target: The app the text is meant for. If another app came to the
    ///   front since (a click elsewhere, a dialog), it is brought back first.
    func insert(_ text: String, into target: NSRunningApplication?) async -> Outcome {
        if let target, !(await PasteTarget.bringToFront(target)) {
            copy(text)
            return .targetUnavailable(appName: target.localizedName)
        }
        guard FocusedElement.current() != .notText else {
            copy(text)
            return .noTextField
        }

        let pasteboard = NSPasteboard.general
        let saved = Self.snapshot(pasteboard)

        let item = NSPasteboardItem()
        item.setString(text, forType: .string)
        item.setData(Data(), forType: Self.transientType)
        item.setData(Data(), forType: Self.autoGeneratedType)
        pasteboard.clearContents()
        pasteboard.writeObjects([item])
        let ourChangeCount = pasteboard.changeCount

        Self.postPaste()

        Task {
            try? await Task.sleep(for: Self.restoreDelay)
            // If something else wrote to the clipboard meanwhile, leave it alone.
            guard pasteboard.changeCount == ourChangeCount else { return }
            pasteboard.clearContents()
            if !saved.isEmpty { pasteboard.writeObjects(saved) }
        }
        return .pasted
    }

    /// Puts the text on the clipboard as an ordinary copy the user keeps.
    func copy(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
    }

    /// Copies concrete data for every type on every item (lazily promised data from
    /// other apps is materialised here or lost).
    private static func snapshot(_ pasteboard: NSPasteboard) -> [NSPasteboardItem] {
        (pasteboard.pasteboardItems ?? []).map { original in
            let copy = NSPasteboardItem()
            for type in original.types {
                if let data = original.data(forType: type) { copy.setData(data, forType: type) }
            }
            return copy
        }
    }

    private static func postPaste() {
        let source = CGEventSource(stateID: .combinedSessionState)
        let key = CGKeyCode(kVK_ANSI_V)
        let down = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: true)
        let up = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: false)
        down?.flags = .maskCommand
        up?.flags = .maskCommand
        down?.post(tap: .cghidEventTap)
        up?.post(tap: .cghidEventTap)
    }
}

/// Makes sure the app a dictation is meant for is frontmost before ⌘V is sent.
enum PasteTarget {
    /// Lets the app make its window key after it comes back to the front.
    private static let settleDelay: Duration = .milliseconds(100)
    private static let pollInterval: Duration = .milliseconds(20)

    /// The app that should receive a paste right now. Taken when the user finishes
    /// speaking, which is when the cursor is where they want the text.
    static func current() -> NSRunningApplication? {
        NSWorkspace.shared.frontmostApplication
    }

    /// Returns false if the app quit or refused to come to the front.
    static func bringToFront(_ app: NSRunningApplication) async -> Bool {
        if app.isTerminated { return false }
        if isFrontmost(app) { return true }
        DebugTrace.write("paste: target lost focus, reactivating")
        app.activate()
        if await waitUntilFrontmost(app, timeout: .milliseconds(300)) {
            try? await Task.sleep(for: settleDelay)
            return true
        }
        // macOS 14's cooperative activation lets the system ignore a background app's
        // request to activate another app; Accessibility can still raise it.
        let element = AXUIElementCreateApplication(app.processIdentifier)
        AXUIElementSetAttributeValue(element, kAXFrontmostAttribute as CFString, kCFBooleanTrue)
        guard await waitUntilFrontmost(app, timeout: .milliseconds(500)) else {
            DebugTrace.write("paste: target did not come to the front")
            return false
        }
        try? await Task.sleep(for: settleDelay)
        return true
    }

    private static func isFrontmost(_ app: NSRunningApplication) -> Bool {
        NSWorkspace.shared.frontmostApplication?.processIdentifier == app.processIdentifier
    }

    private static func waitUntilFrontmost(_ app: NSRunningApplication, timeout: Duration) async -> Bool {
        let deadline = ContinuousClock.now + timeout
        while ContinuousClock.now < deadline {
            if isFrontmost(app) { return true }
            if app.isTerminated { return false }
            try? await Task.sleep(for: pollInterval)
        }
        return isFrontmost(app)
    }
}

/// What has keyboard focus in the frontmost app, as far as Accessibility can tell.
///
/// Only `.notText` changes behaviour, so it is reserved for controls that clearly can't
/// take typed text. Anything AX can't describe (custom-drawn terminals and editors,
/// web areas, apps that time out) counts as `.unknown` and still gets ⌘V.
enum FocusedElement: Equatable {
    case text
    case notText
    case unknown

    /// Roles that never accept typed text unless the element also exposes a text selection.
    private static let nonTextRoles: Set<String> = [
        kAXButtonRole, kAXCheckBoxRole, kAXRadioButtonRole, kAXPopUpButtonRole,
        kAXMenuButtonRole, kAXMenuItemRole, kAXDisclosureTriangleRole, kAXSliderRole,
        kAXListRole, kAXOutlineRole, kAXTableRole, kAXRowRole, kAXBrowserRole,
        kAXImageRole, kAXStaticTextRole, kAXTabGroupRole, kAXToolbarRole, "AXLink",
    ]
    private static let textRoles: Set<String> = [
        kAXTextFieldRole, kAXTextAreaRole, kAXComboBoxRole, "AXSearchField",
    ]
    /// Keeps a hung frontmost app from stalling the paste.
    private static let messagingTimeout: Float = 0.25

    static func current() -> FocusedElement {
        // Accessibility can't see into our own windows reliably. ⌘V with no text view
        // focused there makes macOS play its alert sound on top of the stop cue.
        if NSWorkspace.shared.frontmostApplication?.processIdentifier == ProcessInfo.processInfo.processIdentifier {
            return NSApp.keyWindow?.firstResponder is NSText ? .text : .notText
        }
        let systemWide = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(systemWide, messagingTimeout)
        var focused: CFTypeRef?
        guard AXUIElementCopyAttributeValue(systemWide, kAXFocusedUIElementAttribute as CFString, &focused) == .success,
              let focused, CFGetTypeID(focused) == AXUIElementGetTypeID() else { return .unknown }
        let element = focused as! AXUIElement
        AXUIElementSetMessagingTimeout(element, messagingTimeout)

        var roleValue: CFTypeRef?
        guard AXUIElementCopyAttributeValue(element, kAXRoleAttribute as CFString, &roleValue) == .success,
              let role = roleValue as? String else { return .unknown }
        if textRoles.contains(role) { return .text }
        // Web content and custom views can be editable whatever their role says.
        var settable = DarwinBoolean(false)
        if AXUIElementIsAttributeSettable(element, kAXSelectedTextRangeAttribute as CFString, &settable) == .success,
           settable.boolValue { return .text }
        return nonTextRoles.contains(role) ? .notText : .unknown
    }
}
